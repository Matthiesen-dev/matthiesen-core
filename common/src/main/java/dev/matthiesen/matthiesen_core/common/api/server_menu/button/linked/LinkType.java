package dev.matthiesen.matthiesen_core.common.api.server_menu.button.linked;

/**
 * Represents the type of link between buttons in a server menu, indicating whether the link is to the previous or next button.
 */
public enum LinkType {
    /**
     * Represents a link to the previous button in a sequence.
     */
    Previous,
    /**
     * Represents a link to the next button in a sequence.
     */
    Next
}
