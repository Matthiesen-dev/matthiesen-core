package dev.matthiesen.matthiesen_core.common.api.server_menu.template;

/**
 * Represents the type of line that can be drawn in a server menu template.
 * This enum defines two types of lines: VERTICAL and HORIZONTAL.
 */
public enum LineType {
    /**
     * Represents a vertical line in the server menu template.
     */
    VERTICAL,
    /**
     * Represents a horizontal line in the server menu template.
     */
    HORIZONTAL
}
