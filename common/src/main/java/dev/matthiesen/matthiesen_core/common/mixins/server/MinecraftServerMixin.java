package dev.matthiesen.matthiesen_core.common.mixins.server;

import dev.matthiesen.matthiesen_core.common.api.server_menu.tasks.UITaskManager;
import net.minecraft.server.MinecraftServer;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

@Mixin(MinecraftServer.class)
public abstract class MinecraftServerMixin {
    @Inject(method = "tickServer", at = @At("TAIL"))
    private void matthiesenCore$onTick(CallbackInfo ci) {
        UITaskManager.getInstance().tick();
    }
}
